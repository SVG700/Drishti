"""Pydantic schemas and interface contracts for future AI features.

These models define standard interfaces for future development:
1. AI-powered PAIMANA project assistant
2. Infrastructure project progress forecasting
3. Project delay detection
4. Progress and expenditure anomaly detection
5. AI-generated project reports

Design Rule:
Every AI output model explicitly distinguishes official reported values from
model predictions or AI explanations with source attribution fields.
"""
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class AIAssistantRequest(BaseModel):
    """User query or prompt to the PAIMANA AI assistant."""
    query: str = Field(..., description="Natural language question regarding PAIMANA infrastructure projects")
    project_id: Optional[str] = Field(None, description="Optional target project ID to ground the query")
    include_historical_context: bool = Field(True, description="Whether to inject monthly report trajectory into prompt")


class AIAssistantResponse(BaseModel):
    """AI assistant answer grounded on MoSPI project data."""
    answer: str = Field(..., description="Assistant response text")
    grounded_project_id: Optional[str] = Field(None, description="Associated project ID if contextual")
    official_data_used: Dict[str, Any] = Field(default_factory=dict, description="Verified official figures referenced in response")
    source_attribution: str = Field(default="MoSPI Central Sector Flash Reports (July 2025 - March 2026)")
    disclaimer: str = Field(default="AI-generated interpretation. Official figures originate directly from MoSPI Flash Reports.")


class ProjectForecastResponse(BaseModel):
    """Forecasted completion date and completion cost trajectory."""
    project_id: str
    official_revised_doc: Optional[str] = Field(None, description="Official anticipated commissioning date")
    forecasted_doc: str = Field(..., description="AI/ML projected completion date (YYYY-MM)")
    projected_final_cost_cr: float = Field(..., description="Model estimated final cost in ₹ Crore")
    confidence_score: float = Field(..., description="Statistical confidence (0.0 to 1.0)")
    forecast_method: str = Field(default="Historical Run-Rate & Sector Burn-Rate Regression")
    disclaimer: str = Field(default="Forecasted value generated by predictive model; not an official government target.")


class DelayRiskResponse(BaseModel):
    """Delay risk assessment and early warning indicators."""
    project_id: str
    current_reported_delay_months: float = Field(..., description="Official reported delay from MoSPI")
    predicted_delay_risk_level: str = Field(..., description="Low, Moderate, High, or Critical")
    delay_probability: float = Field(..., description="Probability of further delay (0.0 to 1.0)")
    key_risk_drivers: List[str] = Field(default_factory=list, description="Primary factors driving delay risk")
    disclaimer: str = Field(default="Risk score derived from predictive model; distinct from official status.")


class AnomalyDetectionResponse(BaseModel):
    """Detected irregularities in expenditure run-rate vs physical progress."""
    project_id: str
    anomaly_detected: bool = Field(..., description="Flag indicating statistical deviation")
    anomaly_type: Optional[str] = Field(None, description="e.g., 'Expenditure Surge Without Progress' or 'Progress Stagnation'")
    severity: str = Field(default="Normal", description="Normal, Warning, or Severe")
    details: Dict[str, Any] = Field(default_factory=dict, description="Z-scores, historical velocity comparisons, and ratios")
    disclaimer: str = Field(default="Calculated anomaly indicator for auditor review; does not assert wrongdoing.")


class ProjectReportResponse(BaseModel):
    """AI-synthesized executive project summary report."""
    project_id: str
    project_name: str
    report_title: str
    executive_summary: str
    official_metrics: Dict[str, Any] = Field(..., description="Official metrics from Flash Reports")
    ai_risk_assessment: str = Field(..., description="Synthesized AI assessment of project health")
    recommended_interventions: List[str] = Field(default_factory=list)
    generated_at: str
    model_version: str
    disclaimer: str = Field(default="AI-generated report. Always cross-reference with official MoSPI Flash Reports.")
